    scd Nullable(Float64),
    term_elapsed_time Nullable(Float64),
    term_setup_time Nullable(DateTime64(3, 'UTC')),
    term_connect_time Nullable(DateTime64(3, 'UTC')),
    term_disconnect_time Nullable(DateTime64(3, 'UTC')),
