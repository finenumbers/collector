    device_id UUID,
    file_id UUID,
    row_number UInt64,
    ingested_at DateTime64(3, 'UTC'),
    parser_version LowCardinality(String),
    template_key LowCardinality(String),
    cdr_id String,
    cdr_date Nullable(DateTime64(3, 'UTC')),
    setup_time Nullable(DateTime64(3, 'UTC')),
    connect_time Nullable(DateTime64(3, 'UTC')),
    disconnect_time Nullable(DateTime64(3, 'UTC')),
    duration_ms Nullable(UInt64),
    elapsed_time Nullable(Float64),
    outcome LowCardinality(String),
    in_ani String,
    in_dnis String,
    out_ani String,
    out_dnis String,
    bill_ani String,
    bill_dnis String,
    src_user String,
    dst_user String,
    radius_user String,
    src_name String,
    dst_name String,
    dp_name String,
    in_cpc LowCardinality(String),
    out_cpc LowCardinality(String),
    in_zone String,
    out_zone String,
    in_orig_dnis String,
    out_orig_dnis String,
    in_ani_type_of_number LowCardinality(String),
    in_dnis_type_of_number LowCardinality(String),
    out_ani_type_of_number LowCardinality(String),
    out_dnis_type_of_number LowCardinality(String),
    in_orig_dnis_type_of_number LowCardinality(String),
    out_orig_dnis_type_of_number LowCardinality(String),
    ext_ani_type_of_number LowCardinality(String),
    ext_dnis_type_of_number LowCardinality(String),
    ext_orig_dnis_type_of_number LowCardinality(String),
    in_ani_screening LowCardinality(String),
    in_ani_presentation LowCardinality(String),
    out_ani_screening LowCardinality(String),
    out_ani_presentation LowCardinality(String),
    in_lrn String,
    retrieved_lrn String,
    lrn String,
    ext_lrn String,
    out_lrn String,
    lnp_server String,
    signal_node_name String,
    src_gatekeeper_address String,
    remote_src_sig_address String,
    remote_dst_sig_address String,
    remote_src_media_address String,
    remote_dst_media_address String,
    local_src_sig_address String,
    local_dst_sig_address String,
    local_src_media_address String,
    local_dst_media_address String,
    in_leg_proto LowCardinality(String),
    out_leg_proto LowCardinality(String),
    in_leg_transport_proto LowCardinality(String),
    out_leg_transport_proto LowCardinality(String),
    conf_id String,
    in_leg_call_id String,
    out_leg_call_id String,
