    raw_fields Map(String, String),
    source_timezone LowCardinality(String),
    source_utc_offset_minutes Int16,
    timezone_revision UInt64
)
ENGINE = ReplacingMergeTree(ingested_at)
PARTITION BY toYYYYMM(coalesce(setup_time, cdr_date, ingested_at))
ORDER BY (device_id, cdr_id, record_id)
TTL toDateTime(coalesce(setup_time, cdr_date, ingested_at)) + INTERVAL 1095 DAY DELETE;

CREATE TABLE IF NOT EXISTS collector.satel_rtu_cdr_time_facts
(
    device_id UUID,
    timezone_revision UInt64,
    record_id UUID,
    interpreted_at DateTime64(6, 'UTC'),
    cdr_date_utc Nullable(DateTime64(3, 'UTC')),
    setup_time_utc Nullable(DateTime64(3, 'UTC')),
    connect_time_utc Nullable(DateTime64(3, 'UTC')),
    disconnect_time_utc Nullable(DateTime64(3, 'UTC')),
    term_setup_time_utc Nullable(DateTime64(3, 'UTC')),
    term_connect_time_utc Nullable(DateTime64(3, 'UTC')),
    term_disconnect_time_utc Nullable(DateTime64(3, 'UTC')),
    source_timezone LowCardinality(String),
    source_utc_offset_minutes Int16
)
ENGINE = ReplacingMergeTree(interpreted_at)
PARTITION BY toYYYYMM(coalesce(setup_time_utc, cdr_date_utc, interpreted_at))
ORDER BY (device_id, timezone_revision, record_id)
TTL toDateTime(interpreted_at) + INTERVAL 1095 DAY DELETE;
