    term_scd Nullable(Float64),
    src_media_bytes_in Nullable(UInt64),
    src_media_bytes_out Nullable(UInt64),
    dst_media_bytes_in Nullable(UInt64),
    dst_media_bytes_out Nullable(UInt64),
    src_media_packets Nullable(UInt64),
    dst_media_packets Nullable(UInt64),
